def resolve():
    rows = {}
    for name, grid in ICONS:
        if grid is None:
            if name == 'right':
                grid = [r[::-1] for r in rows['left']]
            elif name == 'down':
                grid = list(reversed(rows['up']))
        assert len(grid) == 16 and all(len(r) == 16 for r in grid), name
        rows[name] = grid
    return [rows[n] for n, _ in ICONS]


if __name__ == '__main__':
    grids = resolve()
    w, h = 16 * len(grids), 16
    px = bytearray(w * h * 4)
    for i, g in enumerate(grids):
        for y, row in enumerate(g):
            for x, ch in enumerate(row):
                if ch == '#':
                    j = (y * w + i * 16 + x) * 4
                    px[j:j + 4] = b'\xff\xff\xff\xff'
    here = os.path.dirname(os.path.abspath(__file__))
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.normpath(os.path.join(here, '../../../../game/assets/front/icons.png'))
    os.makedirs(os.path.dirname(out), exist_ok=True)
    write_png(out, w, h, px)
    print('icons ->', out, [n for n, _ in ICONS])
